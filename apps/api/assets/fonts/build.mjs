// Regenerates apps/api/src/cards/fonts.gen.ts from the TTFs next to this script.
//
// satori needs font bytes, and neither of the two bundlers this Worker goes through reads a binary
// file the same way (wrangler's esbuild would need a `Data` module rule in wrangler.jsonc, which is
// W10-D's file; Vite, which builds the Workers tests, resolves a `.ttf` import to a URL string no
// Worker can fetch). A generated module of base64 strings is the one form both bundle identically.
//
//   node apps/api/assets/fonts/build.mjs
//
// The TTFs themselves come from the same upstream the web uses (@fontsource-variable), instanced to
// the static weights the cards draw with; see README.md.
import { readFile, writeFile } from 'node:fs/promises';

const FILES = [
  ['fredoka-600', 'Fredoka-600.ttf'],
  ['fredoka-700', 'Fredoka-700.ttf'],
  ['inter-500', 'Inter-500.ttf'],
  ['inter-600', 'Inter-600.ttf'],
  ['inter-700', 'Inter-700.ttf'],
];

const here = new URL('./', import.meta.url);
const out = new URL('../../src/cards/fonts.gen.ts', here);

const entries = [];
for (const [key, file] of FILES) {
  const bytes = await readFile(new URL(file, here));
  entries.push(`  '${key}':\n    '${bytes.toString('base64')}',`);
}

await writeFile(
  out,
  `// GENERATED by apps/api/assets/fonts/build.mjs from apps/api/assets/fonts/*.ttf. Do not edit.
// Each value is one static TTF as base64; src/cards/fonts.ts decodes them for satori.

export const FONT_DATA_BASE64 = {
${entries.join('\n')}
} as const;

export type FontKey = keyof typeof FONT_DATA_BASE64;
`,
);
console.log(`wrote ${out.pathname}`);
